// 每個階段用 10 題一個視窗：生活 4～5、工作 4～5、小任務 1（約 45%／45%／10%）
const ICE_BASE = { 2: 0, 3: 1, 5: 2 };   // 各階段使用不同的視窗，避免同一組在不同階段看到重複的題目

function iceRng(seedStr) {
  let h = 1779033703 ^ seedStr.length;
  for (let i = 0; i < seedStr.length; i++) { h = Math.imul(h ^ seedStr.charCodeAt(i), 3432918353); h = (h << 13) | (h >>> 19); }
  return () => { h = Math.imul(h ^ (h >>> 16), 2246822507); h = Math.imul(h ^ (h >>> 13), 3266489909); h ^= h >>> 16; return (h >>> 0) / 4294967296; };
}
function iceShuffle(arr, rnd) { const a = arr.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

// group：組別名稱；stage：階段 id；n：這個階段第幾題（從 0 開始）
function iceQuestion(group, stage, n) {
  const w = ICE_BASE[stage] ?? 0, k = ((n % 10) + 10) % 10;
  const rnd = iceRng("slots|" + group + "|" + stage);
  const lifeN = 4 + (w % 2);
  const slots = iceShuffle([...Array(lifeN).fill("life"), ...Array(9 - lifeN).fill("work"), "task"], rnd);
  const kind = slots[k];
  // 同一類題目在整場工作坊中依固定順序輪流，不重複
  const before = slots.slice(0, k).filter((s) => s === kind).length;
  // 前面視窗已經用掉幾題同類型的題目（生活 4/5、工作 5/4 交替，小任務 1）
  let used = 0; for (let i = 0; i < w; i++) used += kind === "life" ? 4 + (i % 2) : kind === "work" ? 5 - (i % 2) : 1;
  const pos = used + before;
  const deck = { life: ICE_LIFE, work: ICE_WORK, task: ICE_TASK }[kind];
  const order = iceShuffle(deck.map((_, i) => i), iceRng("deck|" + group + "|" + kind));
  return { kind, text: deck[order[pos % deck.length]] };
}

// 投影畫面用：依時間輪播，45%／45%／10%
function iceRotating(tick) {
  const rnd = iceRng("proj|" + tick);
  const r = rnd();
  const deck = r < 0.45 ? ICE_LIFE : r < 0.9 ? ICE_WORK : ICE_TASK;
  return deck[Math.floor(rnd() * deck.length)];
}
